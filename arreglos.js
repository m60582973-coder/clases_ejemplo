//pust=>agregar al final
let lista =[]
lista.push("asss")
console.log(lista)
lista.push("brrrr")
console.log(lista)
// agregar al inicio de un arreglo  unshift
lista.unshift("cvcvcvcv")
console.log(lista)
//pop=>elimina elemento al final
lista.pop("drdrdr")
console.log(lista)
//shift=>eliminar al inicio
lista.shift("rdrdr")
console.log(lista)